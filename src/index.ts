const createPopupWindow = (x: number, y: number): void => {
  log.debug('main', 'Create popup window', { x, y });

  // Get screen dimensions and scale
  const primaryDisplay = screen.getPrimaryDisplay();
  const { width: screenWidth, height: screenHeight } = primaryDisplay.workAreaSize;
  const scaleFactor = primaryDisplay.scaleFactor || 1;

                // Slim strip: width matches 8×24px icons + gaps + padding (keep in sync with popup-new.html strip resize)
              const POPUP_STRIP_ICON = 24;
              const POPUP_STRIP_GAP = 2;
              const POPUP_STRIP_PAD = 4;
              const POPUP_STRIP_ICONS = 8;
              const popupWidth =
                POPUP_STRIP_PAD +
                POPUP_STRIP_ICONS * POPUP_STRIP_ICON +
                (POPUP_STRIP_ICONS - 1) * POPUP_STRIP_GAP;
              const popupHeight = 34; // toolbar ~26px + small frame margin
  
                // Position popup near the selected text, but ensure it stays within screen bounds
              // Convert native (physical px) coordinates to Electron's DIP coordinates
              let popupX = Math.round(x / scaleFactor);
              let popupY = Math.round(y / scaleFactor);

              // Use provided coordinates if valid, otherwise use cursor as fallback
              if (popupX < 0 || popupX > screenWidth || popupY < 0 || popupY > screenHeight || isNaN(popupX) || isNaN(popupY)) {
                const cur = screen.getCursorScreenPoint();
                popupX = cur.x;
                popupY = cur.y;
                log.debug('main', 'Popup position: cursor fallback', { popupX, popupY });
              } else {
                log.debug('main', 'Popup position: selection', { popupX, popupY });
              }
              
              // Adjust position to show popup near the text, not under the cursor
              // Place popup slightly to the right and below the selection to avoid covering text
              const offsetX = 18; // move right
              const offsetY = 14; // move down
              popupX = Math.max(10, Math.min(popupX - Math.floor(popupWidth / 2) + offsetX, screenWidth - popupWidth - 10));
              popupY = Math.max(10, Math.min(popupY + offsetY, screenHeight - popupHeight - 10));
              
              // Ensure popup stays within screen bounds
              if (popupX < 10) popupX = 10;
              if (popupY < 10) popupY = 10;
              if (popupX + popupWidth > screenWidth) {
                popupX = screenWidth - popupWidth - 10;
              }
              if (popupY + popupHeight > screenHeight) {
                popupY = screenHeight - popupHeight - 10;
              }
              log.debug('main', 'Popup bounds', { popupX, popupY, popupWidth, popupHeight });

  // Coalesce duplicate requests for the same text within a short period
  const textForPopup = (lastSelectionEvent && (lastSelectionEvent.text || '').trim()) || lastSelectedText || '';
  const nowTs = Date.now();
  if (textForPopup && lastPopupText === textForPopup && (nowTs - lastPopupAt) < 1000) {
    log.debug('main', 'Skip duplicate popup (same text, 1s)');
    return;
  }

  // Additional check: prevent rapid successive popups regardless of text
  if (lastPopupAt && (nowTs - lastPopupAt) < 300) {
    log.debug('main', 'Skip rapid popup (300ms cooldown)');
    return;
  }

  // Commit immediately — do not wait for did-finish-load. Otherwise shortcut mode can
  // double-open: selection (keys held) + global trigger fire almost together, both pass
  // cooldown because lastPopupAt was still unset from the async popup path.
  lastPopupAt = nowTs;
  lastPopupText = textForPopup;

  // If a popup already exists, reuse it by moving and updating content (but do not resize here)
  const existing = popupWindows.find(win => win && !win.isDestroyed());
  if (existing) {
    try {
      // Only move; size will be managed by renderer's one-time request
      const [currW, currH] = existing.getSize();
      existing.setBounds({ x: popupX, y: popupY, width: currW, height: currH }, false);
      existing.show();
      try { existing.focus(); } catch {}
      if (textForPopup) existing.webContents.send('popup-text', textForPopup);
      log.debug('main', 'Reuse existing popup');
      return;
    } catch (e) {
      log.warn('main', 'Popup reuse failed, creating new', { err: String(e) });
    }
  }

                const newPopupWindow = new BrowserWindow({
                width: popupWidth,
                height: popupHeight,
                x: popupX,
                y: popupY,
                frame: false,
                resizable: true,
                alwaysOnTop: true,
                skipTaskbar: true, // Hide from taskbar as requested
                focusable: true,
                show: false,
                transparent: false,
                minWidth: 160,
                minHeight: 28,
                maxWidth: 1200,
                maxHeight: 900,
                movable: true, // Make window draggable
                webPreferences: {
                  preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
                  nodeIntegration: false,
                  contextIsolation: true,
                },
              });
  // Close on blur to match intended UX
  newPopupWindow.on('blur', () => {
    // Use a shorter timeout to be more responsive, but still allow for focus transitions
    setTimeout(() => {
      try {
        if (newPopupWindow.isDestroyed()) return;

        const focused = BrowserWindow.getFocusedWindow();
        const isPopupFocused = focused === newPopupWindow;

        // Only close if popup is not focused and no other app windows are focused
        // This prevents closing when user clicks between app windows
        if (!isPopupFocused && (!focused || !popupWindows.includes(focused))) {
          log.debug('main', 'Close popup on blur');
          newPopupWindow.close();
        } else {
          log.debug('main', 'Keep popup (focus)');
        }
      } catch (e) {
        log.warn('main', 'Popup blur check failed', { err: String(e) });
      }
    }, 150); // Reduced from 250ms to be more responsive
  });
// (moved) wiki handler registered at top-level below

  // Add error handling for load failures
  newPopupWindow.webContents.on('did-fail-load', (event, errorCode, errorDescription, validatedURL) => {
    log.error('main', 'Popup load failed', { errorCode, errorDescription, validatedURL });
  });

  // FIXED: Load the correct HTML file for the new popup using webpack entry point
  // Load the dedicated popup bundle (popup-new.html) without #popup so its own DOM is used
  const popupUrl = withPopupDevFlag(POPUP_WINDOW_WEBPACK_ENTRY);
  newPopupWindow.loadURL(popupUrl).catch((error) => {
    log.error('main', 'Popup loadURL failed', { err: String(error) });
  });

  // After the popup finishes loading, send the selected text to the renderer
  newPopupWindow.webContents.on('did-finish-load', () => {
    try {
      const textToSend = (lastSelectionEvent && lastSelectionEvent.text) || lastSelectedText || '';
      if (textToSend) {
        newPopupWindow.webContents.send('popup-text', textToSend);
      }
      lastPopupText = textToSend;
    } catch (e) {
      log.warn('main', 'Send popup-text failed', { err: String(e) });
    }
  });

  // Show popup when ready
  newPopupWindow.once('ready-to-show', () => {
    newPopupWindow.show();
    try { newPopupWindow.focus(); } catch {}
  });

                newPopupWindow.on('closed', () => {
                popupWindows = popupWindows.filter(win => win !== newPopupWindow);

                // Reset selection state to allow same word to trigger popup again
                lastSelectionEvent = null; // Reset the main process selection state
                lastSelectedText = ''; // Reset the last selected text
              });

  popupWindows.push(newPopupWindow);
};

const createSettingsWindow = (): void => {
  if (settingsWindow && !settingsWindow.isDestroyed()) {
    settingsWindow.focus();
    return;
  }

  settingsWindow = new BrowserWindow({
    width: 600,
    height: 700,
    parent: mainWindow || undefined,
    modal: true,
    webPreferences: {
      preload: MAIN_WINDOW_PRELOAD_WEBPACK_ENTRY,
      nodeIntegration: false,
      contextIsolation: true,
    },
    show: false,
    frame: false,
  });

  const settingsUrl = MAIN_WINDOW_WEBPACK_ENTRY + '#settings';
  settingsWindow.loadURL(settingsUrl);

  settingsWindow.once('ready-to-show', () => {
    settingsWindow.show();
  });

  settingsWindow.on('closed', () => {
    settingsWindow = null;
  });
  // Allow ESC to close via IPC from renderer
  settingsWindow.webContents.on('before-input-event', (_event, input) => {
    if (input.key === 'Escape') {
      settingsWindow?.close();
    }
  });
};

function registerNativeSelectionHandlerOnce(): void {
  if (nativeSelectionHandlerRegistered) {
    return;
  }
  nativeSelectionHandlerRegistered = true;
  nativeSelectionService.onSelection((event: SelectionEvent) => {
    const focused = BrowserWindow.getFocusedWindow();
    if (
      focused &&
      (popupWindows.includes(focused) ||
        focused === mainWindow ||
        focused === settingsWindow ||
        externalWindows.includes(focused))
    ) {
      return;
    }

    lastSelectionEvent = event;

    if (monitorSettings.mode === 'shortcut') {
      try {
        mainWindow?.webContents.send('selection-changed', event.text);
      } catch (e) {
        log.warn('main', 'selection-changed IPC failed', { err: String(e) });
      }
      // Popup if trigger is held when selection lands, or after selection via global trigger callback.
      if (isAcceleratorPhysicallyHeld(monitorSettings.triggerShortcut)) {
        createPopupWindow(event.x, event.y);
      }
      return;
    }

    try {
      mainWindow?.webContents.send('selection-changed', event.text);
    } catch (e) {
      log.warn('main', 'selection-changed IPC failed', { err: String(e) });
    }
    createPopupWindow(event.x, event.y);
  });
}

function startSelectionMonitoring(): void {
  log.debug('main', 'Start native selection monitoring');

  if (nativeSelectionActive) {
    return;
  }

  const isAdmin = checkAdminPrivileges();

  if (!isAdmin) {
    log.warn('main', 'Not running as administrator; UIAutomation may be limited');
  }

  nativeSelectionActive = true;

  try {
    registerNativeSelectionHandlerOnce();

    nativeSelectionService
      .start()
      .then(() => {
        log.info('main', 'Native selection service started');
        updateTrayContextMenu();
      })
      .catch((error) => {
        nativeSelectionActive = false;
        log.error('main', 'Failed to start native selection', { err: String(error) });
        if (!isAdmin) {
          log.error('main', 'Try running as Administrator for UIAutomation');
        }
        updateTrayContextMenu();
      });
  } catch (error: any) {
    log.error('main', 'Start selection monitoring failed', { err: String(error), stack: error?.stack });
    nativeSelectionActive = false;
  }
}

async function stopSelectionMonitoring(): Promise<void> {
  if (!nativeSelectionActive) {
    return;
  }

  try {
    nativeSelectionActive = false;
    log.debug('main', 'Stopping selection monitoring');

    await nativeSelectionService.stop();
    log.info('main', 'Native selection service stopped');
  } catch (error) {
    log.error('main', 'Stop selection monitoring failed', { err: String(error) });
  }
  updateTrayContextMenu();
}

