function createTray(): void {
  if (tray && !tray.isDestroyed()) {
    return;
  }
  let image: Electron.NativeImage;
  try {
    image = nativeImage.createFromPath(getTrayIconPath());
    if (image.isEmpty()) {
      throw new Error('tray image empty');
    }
  } catch {
    try {
      image = nativeImage.createFromDataURL(`data:image/png;base64,${TRAY_FALLBACK_PNG}`);
    } catch {
      image = nativeImage.createEmpty();
    }
  }
  // Downscale large assets so the tray uses most of the glyph (avoids tiny centered artwork).
  if (!image.isEmpty()) {
    const { width, height } = image.getSize();
    const targetPx = process.platform === 'darwin' ? 44 : 32;
    if (width > targetPx || height > targetPx) {
      image = image.resize({ width: targetPx, height: targetPx, quality: 'best' });
    }
  }
  tray = new Tray(image);
  tray.setToolTip('Phevere — dictionary & selection');
  tray.setContextMenu(buildTrayContextMenu());
  tray.on('click', () => {
    showOrRestoreMainWindow();
  });
}

